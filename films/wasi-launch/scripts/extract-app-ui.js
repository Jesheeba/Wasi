// Copies the real app sidebar out of the root index.html into scenes/app-ui.js, so the
// app windows in the film use the product's own markup (and index.css styles it).
// ids are stripped so index.css's id rules (mobile drawer etc.) never apply.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, '..', '..', 'index.html'), 'utf8');
const a = html.indexOf('<aside id="sidebar" class="sidebar">');
const b = html.indexOf('</aside>', a);
if (a < 0 || b < 0) throw new Error('sidebar markup not found in index.html');
const sidebar = html.slice(a, b + 8).replace(/<!--[\s\S]*?-->/g, '').replace(/\s(id|aria-[a-z]+|tabindex|role)="[^"]*"/g, '').replace(/\s+\n/g, '\n');
fs.writeFileSync(path.join(ROOT, 'scenes', 'app-ui.js'), `// generated by scripts/extract-app-ui.js from index.html - do not edit\nwindow.APP_SIDEBAR = ${JSON.stringify(sidebar)};\n`);
console.log(`app-ui.js written (sidebar ${sidebar.length} chars)`);
// index.css pulls fonts from Google with @import; the film self-hosts them (scenes/fonts),
// so a copy without the import keeps rendering independent of the network.
const css = fs.readFileSync(path.join(ROOT, '..', '..', 'index.css'), 'utf8').replace(/@import[^;]+;/g, '');
fs.writeFileSync(path.join(ROOT, 'scenes', 'app.css'), '/* generated by scripts/extract-app-ui.js from index.css - do not edit */\n' + css);
console.log('app.css written');
